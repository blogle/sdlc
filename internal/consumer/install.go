func Install(root, contract string, check bool) error {
	lockBytes, err := os.ReadFile(filepath.Join(root, "flake.lock"))
	if err != nil {
		return err
	}
	var lock struct {
		Nodes map[string]json.RawMessage `json:"nodes"`
	}
	if err := json.Unmarshal(lockBytes, &lock); err != nil {
		return err
	}
	var rootNode struct {
		Inputs map[string]json.RawMessage `json:"inputs"`
	}
	if err := json.Unmarshal(lock.Nodes["root"], &rootNode); err != nil {
		return err
	}
	inputs, ok := rootNode.Inputs["sdlc"]
	if !ok {
		if check {
			fmt.Println("SDLC self-onboarding is deferred")
			return nil
		}
		return fmt.Errorf("add a pinned sdlc input before generating consumer adapters")
	}
	var nodeName string
	if err := json.Unmarshal(inputs, &nodeName); err != nil {
		var nested []string
		if err := json.Unmarshal(inputs, &nested); err != nil || len(nested) == 0 {
			return fmt.Errorf("invalid SDLC flake.lock input")
		}
		nodeName = nested[0]
	}
	locked, ok := lock.Nodes[nodeName]
	if !ok {
		return fmt.Errorf("flake.lock SDLC node %q is missing", nodeName)
	}
	var node struct {
		Original struct {
			Type  string `json:"type"`
			Owner string `json:"owner"`
			Repo  string `json:"repo"`
			Ref   string `json:"ref"`
		} `json:"original"`
		Locked struct {
			Rev string `json:"rev"`
		} `json:"locked"`
	}
	if err := json.Unmarshal(locked, &node); err != nil {
		return err
	}
	if node.Original.Type != "github" || node.Original.Owner != "blogle" || node.Original.Repo != "sdlc" || node.Original.Ref != "v2" {
		return fmt.Errorf("flake.nix must subscribe to the compatible \"github:blogle/sdlc/v2\" channel")
	}
	revision := node.Locked.Rev
	if !regexp.MustCompile(`^[0-9a-f]{40}$`).MatchString(revision) {
		return fmt.Errorf("flake.lock must pin SDLC to a full GitHub commit")
	}
	generated := adapterFiles(revision)
	mergify, err := os.ReadFile(filepath.Join(contract, ".mergify.yml"))
	if err != nil {
		return err
	}
	generated[".mergify.yml"] = string(mergify)
	generated["renovate.json"] = "{\n  \"$schema\": \"https://docs.renovatebot.com/renovate-schema.json\",\n  \"extends\": [\"github>blogle/sdlc#v1\"]\n}\n"
	native := filepath.Join(root, "renovate.json5")
	if _, err := os.Stat(native); err == nil {
		data, err := os.ReadFile(native)
		if err != nil {
			return err
		}
		var config map[string]any
		if err := json5.NewDecoder(bytes.NewReader(data)).Decode(&config); err != nil {
			return fmt.Errorf("renovate.json5: invalid JSON5: %w", err)
		}
		extends, ok := config["extends"].([]any)
		if !ok || !contains(extends, "github>blogle/sdlc#v1") {
			return fmt.Errorf("renovate.json5 must extend github>blogle/sdlc#v1")
		}
		if _, err := os.Stat(filepath.Join(root, "renovate.json")); err == nil {
			return fmt.Errorf("both renovate.json and renovate.json5 exist; retain one native Renovate config")
		}
		delete(generated, "renovate.json")
	}
	var mismatches []string
	names := make([]string, 0, len(generated))
	for name := range generated {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		expected := generated[name]
		path := filepath.Join(root, name)
		actual, err := os.ReadFile(path)
		if err != nil || string(actual) != expected {
			mismatches = append(mismatches, name)
			if !check {
				if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
					return err
				}
				if err := os.WriteFile(path, []byte(expected), 0o644); err != nil {
					return err
				}
			}
		}
	}
	if check && len(mismatches) > 0 {
		return fmt.Errorf("generated SDLC adapters are stale: %s", strings.Join(mismatches, ", "))
	}
	if !check {
		if err := os.MkdirAll(filepath.Join(root, ".changes"), 0o755); err != nil {
			return err
		}
	}
	if check {
		fmt.Println("SDLC adapters match the locked contract")
	} else {
		fmt.Printf("generated SDLC adapters for %s\n", revision)
	}
	return nil
}

func contains(items []any, want string) bool {
	for _, item := range items {
		if item == want {
			return true
		}
	}
	return false
}

